import {test,expect} from '@playwright/test';
test('shared timeline shows partial coverage, hides gaps and restores active layers',async({page})=>{
 test.setTimeout(60000);
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/?year=2023');
 const search=page.getByRole('textbox',{name:'Search map layers'});
 await search.fill('sanitat-farmacies');
 const card=page.locator('.dataset-card');
 await card.getByRole('switch').click();
 await expect(card.getByRole('status')).toContainText('No data for 2023',{timeout:120000});
 await expect(card.getByRole('switch')).toHaveAttribute('aria-checked','true');
 await expect(page.getByRole('button',{name:'2023',exact:true})).toHaveClass(/coverage-partial/);
 await expect(page.locator('.map-footer')).toContainText('0 catalog overlays');
 await page.getByRole('button',{name:'2026',exact:true}).click();
 await expect(card.locator('.layer-details')).toContainText('1,135 features');
 await expect(page.locator('.map-footer')).toContainText('1 catalog overlays');
 await expect(page.locator('.map-footer')).toContainText('0 selected records');
 await page.getByRole('button',{name:'2024',exact:true}).click();
 await expect(card.getByRole('status')).toContainText('No data for 2024');
 await expect(card.locator('.layer-details')).toHaveCount(0);
 await page.getByRole('button',{name:'2026',exact:true}).click();
 await page.reload();
 await search.fill('sanitat-farmacies');
 await expect(card.locator('.layer-details')).toContainText('1,135 features',{timeout:120000});
 await page.getByRole('button',{name:'Data & sources'}).click();
 await expect(page.getByRole('dialog').getByRole('heading',{name:'Every layer has a source.'})).toBeVisible();
 await page.keyboard.press('Escape');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.waitForTimeout(250); // Let the responsive sidebar transition finish.
 await expect(page.getByRole('button',{name:'2026',exact:true})).toBeInViewport();
 await page.screenshot({path:'test-results/timeline-mobile.png'});
 expect(errors).toEqual([]);
});

test('two annual layers switch together, retry failures and discard superseded years',async({page})=>{
 test.setTimeout(60000);
 await page.goto('/?year=2023');
 await page.getByRole('textbox',{name:'Search map layers'}).fill('renda-disponible-llars-bcn');
 const income=page.locator('.dataset-card');
 await income.getByRole('switch').click();
 await expect(income.locator('.layer-details')).toContainText('1,068 features',{timeout:120000});
 await income.locator('.layer-details > summary').click();
 const metric=await income.locator('.overlay-metric select').inputValue();
 await page.route('**/api/resource/renda-disponible-llars-bcn/**',route=>route.fulfill({status:503,json:{detail:'Temporary year outage'}}));
 await page.getByRole('button',{name:'2022',exact:true}).click();
 await expect(income.getByRole('alert')).toContainText('Temporary year outage');
 await expect(income.locator('.layer-details')).toHaveCount(0);
 await expect(page.locator('.map-footer')).toContainText('1 catalog overlays',{timeout:120000});
 await expect(income.getByRole('alert')).toContainText('Temporary year outage');
 await page.unroute('**/api/resource/renda-disponible-llars-bcn/**');
 await income.getByRole('button',{name:'Retry year'}).click();
 await expect(income.locator('.overlay-period')).toContainText('2022',{timeout:120000});
 await expect(income.locator('.overlay-metric select')).toHaveValue(metric);
 await expect(page.locator('.map-footer')).toContainText('2 catalog overlays',{timeout:120000});
 await expect(page.locator('.timeline-coverage')).toContainText('2 of 2 active layers cover 2022');
 await page.getByRole('button',{name:'2021',exact:true}).click();
 await page.getByRole('button',{name:'2023',exact:true}).click();
 await expect(income.locator('.overlay-period')).toContainText('2023',{timeout:120000});
 await expect(page.locator('.map-footer')).toContainText('1 catalog overlays',{timeout:120000});
 await expect(page.locator('.map-footer')).toContainText('7,724 selected records');
 await page.getByRole('textbox',{name:'Search map layers'}).fill('');
 await page.getByLabel('Show active layers only').check();
 await expect(page.locator('.overlay-period')).toHaveCount(1);
 await expect(page.getByRole('switch',{name:'Traffic accidents',exact:true})).toHaveAttribute('aria-checked','true');
 for(const period of await page.locator('.overlay-period').all())await expect(period).toContainText('2023');
 await page.screenshot({path:'test-results/timeline-multiple.png'});
});
